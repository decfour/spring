CREATE TABLE member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL UNIQUE REFERENCES member(id),
    balance NUMERIC(19, 4) NOT NULL CHECK (balance >= 0),
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    exchange VARCHAR(30) NOT NULL
);

CREATE TABLE holding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account(id),
    stock_id BIGINT NOT NULL REFERENCES stock(id),
    quantity BIGINT NOT NULL CHECK (quantity >= 0),
    avg_price NUMERIC(19, 4) NOT NULL CHECK (avg_price >= 0),
    CONSTRAINT uk_holding_account_stock UNIQUE (account_id, stock_id)
);

CREATE TABLE trade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account(id),
    stock_id BIGINT NOT NULL REFERENCES stock(id),
    type VARCHAR(10) NOT NULL CHECK (type IN ('BUY', 'SELL')),
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    price NUMERIC(19, 4) NOT NULL CHECK (price > 0),
    executed_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE chat_room (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    stock_id BIGINT NOT NULL REFERENCES stock(id),
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id BIGINT NOT NULL REFERENCES chat_room(id),
    member_id BIGINT NOT NULL REFERENCES member(id),
    content VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

